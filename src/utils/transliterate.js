// src/utils/transliterate.js
// Узбекская латиница → кириллица. Сохраняем регистр.

const MULTI = [
    // трёхсимвольные с апострофами
    ["oʻ", "ў"], ["o‘", "ў"], ["o'", "ў"],
    ["gʻ", "ғ"], ["g‘", "ғ"], ["g'", "ғ"],
    // двухсимвольные
    ["sh", "ш"], ["Sh", "Ш"], ["SH", "Ш"],
    ["ch", "ч"], ["Ch", "Ч"], ["CH", "Ч"],
    ["yo", "ё"], ["Yo", "Ё"], ["YO", "Ё"],
    ["yu", "ю"], ["Yu", "Ю"], ["YU", "Ю"],
    ["ya", "я"], ["Ya", "Я"], ["YA", "Я"],
    ["ye", "е"], ["Ye", "Е"], ["YE", "Е"],
    ["ts", "ц"], ["Ts", "Ц"], ["TS", "Ц"],
    ["ng", "нг"], ["Ng", "нг"], ["NG", "нг"],
  ];
  
  const SINGLE = {
    a: "а", b: "б", d: "д", e: "е", f: "ф", g: "г", h: "ҳ",
    i: "и", j: "ж", k: "к", l: "л", m: "м", n: "н", o: "о",
    p: "п", q: "қ", r: "р", s: "с", t: "т", u: "у", v: "в",
    x: "х", y: "й", z: "з",
    A: "А", B: "Б", D: "Д", E: "Е", F: "Ф", G: "Г", H: "Ҳ",
    I: "И", J: "Ж", K: "К", L: "Л", M: "М", N: "Н", O: "О",
    P: "П", Q: "Қ", R: "Р", S: "С", T: "Т", U: "У", V: "В",
    X: "Х", Y: "Й", Z: "З",
    // спецсимволы
    "ʻ": "", "‘": "", "’": "", "'": "",
  };
  
  export function toCyrillic(input) {
    if (!input) return input;
    let s = String(input);
  
    // 1) многосимвольные — проходим в цикле, заменяя по одному вхождению
    for (const [from, to] of MULTI) {
      s = s.split(from).join(to);
    }
  
    // 2) одиночные
    let out = "";
    for (const ch of s) {
      out += SINGLE[ch] ?? ch;
    }
    return out;
  }
  
  // Утилита, чтобы не городить if в компонентах
  export function tr(text, lang) {
    return lang === "cyr" ? toCyrillic(text) : text;
  }